#!/usr/bin/env python3

"""Extract K3 range benchmark coordinates into CSV and PGFPlots data."""

from __future__ import annotations

import argparse
import csv
import re
from pathlib import Path


COORDINATE = re.compile(
    r"\(\s*([0-9]+)\s*,\s*([0-9.eE+\-]+)\s*\)"
)
BENCHMARK = re.compile(r"^(range-benchmark-.+)\.txt$")
SHARE = re.compile(r"^share-([0-9]+)$")


def read_manifest(directory: Path) -> dict[str, str]:
    manifest = directory / "manifest.txt"
    values: dict[str, str] = {}
    if manifest.exists():
        for line in manifest.read_text().splitlines():
            if "=" in line:
                key, value = line.split("=", 1)
                values[key] = value
    return values


def metadata(path: Path) -> tuple[str, str, dict[str, str]]:
    values = read_manifest(path.parent)
    share_match = next(
        (SHARE.match(part) for part in path.parts if SHARE.match(part)), None
    )
    share = (
        share_match.group(1)
        if share_match is not None
        else values.get("a100_share", "unknown")
    )
    try:
        root_index = path.parts.index("spacemit-k3")
        compiler = path.parts[root_index + 1]
    except (ValueError, IndexError) as error:
        raise ValueError(f"could not infer compiler from {path}") from error
    return compiler, share, values


def extract(input_dir: Path) -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    for path in sorted(input_dir.rglob("range-benchmark-*.txt")):
        match = BENCHMARK.match(path.name)
        if match is None:
            continue
        compiler, share, manifest = metadata(path)
        coordinates = COORDINATE.findall(path.read_text())
        for index, (dofs, throughput) in enumerate(coordinates):
            rows.append(
                {
                    "benchmark": match.group(1),
                    "compiler": compiler,
                    "share": share,
                    "core_type": manifest.get("core_type", "unknown"),
                    "commit": manifest.get("commit", "unknown"),
                    "point": str(index),
                    "dofs": dofs,
                    "dofs_per_second": throughput,
                    "source": str(path),
                }
            )
    return rows


def write_csv(path: Path, rows: list[dict[str, str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fields = [
        "benchmark",
        "compiler",
        "share",
        "core_type",
        "commit",
        "point",
        "dofs",
        "dofs_per_second",
        "source",
    ]
    with path.open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def write_pgfplots(path: Path, rows: list[dict[str, str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    groups: dict[tuple[str, str, str], list[dict[str, str]]] = {}
    for row in rows:
        key = (row["benchmark"], row["compiler"], row["share"])
        groups.setdefault(key, []).append(row)

    with path.open("w") as stream:
        stream.write("% Generated by extract-range-results.py\n")
        benchmarks = sorted({key[0] for key in groups})
        for benchmark_index, benchmark in enumerate(benchmarks):
            stream.write("\\begin{tikzpicture}\n")
            stream.write("\\begin{axis}[\n")
            stream.write(
                f"title={{{benchmark.replace('_', ' ')}\\ -- K3 mixed OpenMP}},\n"
            )
            stream.write(
                "width=0.94\\textwidth, height=0.62\\textwidth, "
                "xmode=log, ymode=log, grid=major, "
                "legend style={font=\\tiny}, legend columns=2]\n"
            )
            for (group_benchmark, compiler, share), group in sorted(groups.items()):
                if group_benchmark != benchmark:
                    continue
                stream.write(
                    f"% {benchmark}, compiler={compiler}, A100 share={share}%\n"
                )
                stream.write("\\addplot coordinates {\n")
                for row in group:
                    stream.write(
                        f"  ({row['dofs']}, {row['dofs_per_second']})\n"
                    )
                stream.write("};\n")
                stream.write(
                    "\\addlegendentry{"
                    f"{compiler}, A100 share={share}\\%}}\n"
                )
            stream.write("\\end{axis}\n\\end{tikzpicture}\n")
            if benchmark_index + 1 != len(benchmarks):
                stream.write("\\clearpage\n")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("--csv", type=Path, required=True)
    parser.add_argument("--pgfplots", type=Path, required=True)
    args = parser.parse_args()

    rows = extract(args.input)
    if not rows:
        parser.error(f"no range benchmark coordinates found under {args.input}")
    write_csv(args.csv, rows)
    write_pgfplots(args.pgfplots, rows)
    print(f"extracted {len(rows)} coordinates from {args.input}")
    print(f"csv: {args.csv}")
    print(f"pgfplots: {args.pgfplots}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
